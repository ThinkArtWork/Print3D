@dataclass(slots=True)
class SlicerInfo:
    found: bool
    path: str | None = None
    version: str | None = None
    supports_statistics: bool = False
    supports_datadir: bool = False
    #: ``False`` when ``--help`` printed nothing, so the flag list is unverified.
    help_text_verified: bool = True
    problems: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "found": self.found,
            "path": self.path,
            "version": self.version,
            "supports_statistics": self.supports_statistics,
            "supports_datadir": self.supports_datadir,
            "help_text_verified": self.help_text_verified,
            "problems": list(self.problems),
            "warnings": list(self.warnings),
        }


def probe_slicer(path: Path | str | None) -> SlicerInfo:
    """Run ``--help`` and learn the version and supported flags.

    Silence is not failure.  OrcaSlicer on Windows can exit successfully without
    printing any help text; treating that as "not usable" would disable slicing on
    a working install, so the adapter records that the flags were unverified and
    leaves the final verdict to a real slice.
    """
    if path is None:
        return SlicerInfo(found=False, problems=["no slicer binary found"])

    binary = Path(path).expanduser()
    if not binary.is_file():
        return SlicerInfo(found=False, path=str(binary), problems=["binary does not exist"])

    try:
        proc = processes.run_capture(
            [str(binary), "--help"],
            timeout=30,
            env=clean_env(),
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return SlicerInfo(found=False, path=str(binary), problems=[f"--help failed: {exc}"])

    text = (proc.stdout or "") + "\n" + (proc.stderr or "")
    if not text.strip():
        return SlicerInfo(
            found=True,
            path=str(binary),
            help_text_verified=False,
            warnings=[
                "--help produced no output, so the CLI flags could not be verified; "
                "run one real slice to confirm the adapter works."
            ],
        )
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    version = None
    for line in lines:
        match = _VERSION_RE.search(line)
        if match:
            version = match.group(0)
            break
    if version is None and lines:
        version = lines[0]

    supports_statistics = "--export-statistics" in text
    supports_datadir = "--datadir" in text
    problems: list[str] = []
    if "--load-settings" not in text:
        problems.append("CLI does not advertise --load-settings")
    if "--slice" not in text:
        problems.append("CLI does not advertise --slice")
    return SlicerInfo(
        found=True,
        path=str(binary),
        version=version,
        supports_statistics=supports_statistics,
        supports_datadir=supports_datadir,
        problems=problems,
    )


@dataclass(frozen=True)
class SlicerAdapter:
    """One slicer backend, built through ``registry.create('slicer', name)``."""

    name: str

    def find(self, explicit: str | None = None) -> Path | None:
        return find_slicer(explicit)

    def probe(self, path: Path | str | None) -> SlicerInfo:
        return probe_slicer(path)

    def slice(
        self,
        stl: Path,
        target: TargetSettings,
        workdir: Path,
        **kwargs: Any,
    ) -> SliceResult:
        return slice_stl(stl, target, workdir, **kwargs)


def register_adapters(registry: Registry) -> None:
    """Populate the ``slicer`` kind of *registry* with the built-in backends."""
    for name in SLICER_ADAPTERS:
        registry.register("slicer", name, lambda _name=name: SlicerAdapter(_name), replace=True)


def _profile_path(raw: str | Path, label: str) -> Path:
    path = Path(raw).expanduser()
    if not path.is_file():
        raise ConfigError(
            f"Target {label} preset not found: {path}",
            hint="Point targets.<name>.<machine|process|filament> at an OrcaSlicer preset JSON.",
        )
    return path


def resolve_profiles(target: TargetSettings) -> tuple[Path, Path, list[Path]]:
    """Return the machine, process and filament preset files for a target."""
    if not target.machine or not target.process:
        raise ConfigError(
            f"Target {target.printer_model!r} is missing machine/process profiles",
            hint="Set targets.<name>.machine and targets.<name>.process in config.json.",
        )
    machine = _profile_path(target.machine, "machine")
    process = _profile_path(target.process, "process")
    raw_filaments = target.filament if isinstance(target.filament, list) else [target.filament]
    filaments = [_profile_path(item, "filament") for item in raw_filaments if item]
    if not filaments:
        raise ConfigError(
            f"Target {target.printer_model!r} has no filament preset",
            hint="Set targets.<name>.filament to one or more preset files.",
        )
    return machine, process, filaments


def _vendor_root(machine: Path) -> tuple[Path, Path]:
    """Return ``.../system/<Vendor>`` and its ``<Vendor>.json`` bundle."""
    vendor_dir = machine.parent.parent
    bundle = vendor_dir.parent / f"{vendor_dir.name}.json"
    if not bundle.is_file():
        raise ConfigError(
            f"Vendor bundle not found for {machine.name}: {bundle}",
            hint="Keep presets inside OrcaSlicer's system/<Vendor>/ tree.",
        )
    return vendor_dir, bundle


def _coerce_override(value: Any) -> Any:
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return str(value)
    return value


@dataclass(slots=True)
class PreparedProfiles:
    machine: Path
    process: Path
    filament: list[Path]
    datadir: Path | None = None
    overrides: dict[str, Any] = field(default_factory=dict)
    filament_overrides: dict[str, Any] = field(default_factory=dict)
    options: dict[str, Any] | None = None
    toolhead: int = 0
    warnings: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "machine": str(self.machine),
            "process": str(self.process),
            "filament": [str(item) for item in self.filament],
            "datadir": str(self.datadir) if self.datadir else None,
            "overrides": dict(self.overrides),
            "filament_overrides": dict(self.filament_overrides),
            "options": dict(self.options) if self.options else None,
            "toolhead": int(self.toolhead),
            "warnings": list(self.warnings),
        }


def _expand_filaments(filaments: list[Path], toolhead: int, folder: Path) -> list[Path]:
    """Return one filament file per nozzle up to ``toolhead``.

    OrcaSlicer prints a single-object plate with the first filament unless the
    object is mapped to another one.  Loading ``toolhead + 1`` copies and
    passing ``--load-filament-ids "<toolhead + 1>"`` selects that nozzle while
    keeping every slot on the same material.
    """
    if toolhead <= 0 or not filaments:
        return filaments
    base = filaments[0]
    folder.mkdir(parents=True, exist_ok=True)
    expanded = list(filaments)
    for index in range(1, toolhead + 1):
        target = folder / f"{base.stem}_slot{index + 1}{base.suffix}"
        shutil.copyfile(base, target)
        expanded.append(target)
    return expanded


def _prepare_standalone(
    *,
    machine: Path,
    process: Path,
    filaments: list[Path],
    datadir: Path | None,
    overrides: dict[str, Any],
    filament_overrides: dict[str, str],
    options: dict[str, Any] | None,
    toolhead: int,
    workdir: Path,
    warnings: list[str],
) -> PreparedProfiles:
    """Patch flattened presets that are not inside a vendor bundle.

    Snapmaker U1 profiles are exported as standalone JSON files, so there is
    no ``system/<Vendor>`` tree to copy.  OrcaSlicer accepts these files
    directly, so we only need private copies of the two we modify.
    """
    folder = workdir / "profiles"
    folder.mkdir(parents=True, exist_ok=True)

    def _copy_and_patch(source: Path, values: dict[str, Any]) -> Path:
        target = folder / source.name
        shutil.copyfile(source, target)
        if values:
            data = json.loads(target.read_text(encoding="utf-8-sig"))
            data.update(values)
            target.write_text(
                json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
            )
        return target

    process_copy = _copy_and_patch(process, overrides)
    filament_copy = [_copy_and_patch(item, filament_overrides) for item in filaments]
    filament_copy = _expand_filaments(filament_copy, toolhead, folder)
    warnings.append(
        "process/material overrides were written to standalone copies under the slice "
        "workdir; the installed presets stay untouched"
    )
    return PreparedProfiles(
        machine=machine,
        process=process_copy,
        filament=filament_copy,
        datadir=datadir,
        overrides=overrides,
        filament_overrides=filament_overrides,
        options=options,
        toolhead=toolhead,
        warnings=warnings,
    )


#: Preset JSON is what matters here.  Cover images and bed meshes are GUI assets:
#: skipping them keeps the private copy small without changing preset resolution.
_PROFILE_ASSET_SUFFIXES = (".stl", ".png", ".svg", ".3mf", ".gif", ".jpg", ".webp")


def _copy_profile_tree(source: Path, destination: Path) -> None:
    """Copy a ``system`` profile tree, skipping the GUI assets.

    OrcaSlicer resolves ``inherits`` **across** vendor trees: a Snapmaker
    filament can inherit from the shared ``OrcaFilamentLibrary``, and one preset
    that cannot be resolved makes the whole bundle fail to load.  A private
    datadir therefore has to carry every vendor, not only the one being sliced.

    Symlinks are copied by content rather than recreated: creating a link on
    Windows needs Developer Mode, and a preset tree is small enough that the
    difference does not matter.  Dangling links are skipped rather than fatal.
    """

    def _ignore(directory: str, names: list[str]) -> set[str]:
        return {name for name in names if Path(name).suffix.lower() in _PROFILE_ASSET_SUFFIXES}

    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(source, destination, ignore=_ignore, ignore_dangling_symlinks=True)


def prepare_profiles(
    target: TargetSettings,
    workdir: Path,
    options: SliceOptions | None = None,
) -> PreparedProfiles:
    """Resolve profiles, applying ``overrides`` through a private datadir copy.

    OrcaSlicer resolves preset files inside its datadir bundle, so editing a
    preset requires a copy of the vendor tree.  While we are at it this keeps
    the user's installed profiles untouched.
    """
    machine, process, filaments = resolve_profiles(target)
    datadir = Path(target.datadir).expanduser() if target.datadir else None
    overrides = {key: _coerce_override(value) for key, value in (target.overrides or {}).items()}
    filament_overrides: dict[str, str] = {}
    options_summary: dict[str, Any] | None = None
    warnings: list[str] = []
    toolhead = int(options.toolhead) if options is not None else 0

    if options is not None:
        options_summary = options.resolved()
        overrides.update(options.process_overrides())
        filament_overrides = options.filament_overrides()

    if not overrides and not filament_overrides and toolhead <= 0:
        return PreparedProfiles(
            machine=machine,
            process=process,
            filament=filaments,
            datadir=datadir,
            options=options_summary,
            toolhead=toolhead,
            warnings=warnings,
        )

    try:
        vendor_dir, _bundle = _vendor_root(machine)
    except ConfigError:
        return _prepare_standalone(
            machine=machine,
            process=process,
            filaments=filaments,
            datadir=datadir,
            overrides=overrides,
            filament_overrides=filament_overrides,
            options=options_summary,
            toolhead=toolhead,
            workdir=workdir,
            warnings=warnings,
        )
    source_root = datadir or vendor_dir.parent.parent
    copy_root = workdir / "datadir"
    system_copy = copy_root / "system"
    if not system_copy.exists():
        _copy_profile_tree(vendor_dir.parent, system_copy)

    vendor_copy = system_copy / vendor_dir.name
    machine_copy = vendor_copy / "machine" / machine.name
    process_copy = vendor_copy / "process" / process.name
    filament_copy = [vendor_copy / "filament" / item.name for item in filaments]

    if overrides:
        data = json.loads(process_copy.read_text(encoding="utf-8-sig"))
        data.update(overrides)
        process_copy.write_text(
            json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
        )
    if filament_overrides:
        for item in filament_copy:
            data = json.loads(item.read_text(encoding="utf-8-sig"))
            data.update(filament_overrides)
            item.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    filament_copy = _expand_filaments(filament_copy, toolhead, vendor_copy / "filament")
    warnings.append(
        "process/material overrides were written to a private copy of the vendor profiles; "
        f"the installed profiles stay untouched ({source_root})"
    )
    return PreparedProfiles(
        machine=machine_copy,
        process=process_copy,
        filament=filament_copy,
        datadir=copy_root,
        overrides=overrides,
        filament_overrides=filament_overrides,
        options=options_summary,
        toolhead=toolhead,
        warnings=warnings,
    )


def _duration_seconds(text: str) -> int | None:
    match = _DURATION_RE.search(text)
    if not match:
        return None
    hours, minutes, seconds = (int(part or 0) for part in match.groups())
    return hours * 3600 + minutes * 60 + seconds


#: OrcaSlicer splits its metadata across two blocks: the header block (layer
#: count, generated-by) is at the top, while ``filament used``, ``printer_model``
#: and ``estimated printing time`` sit in a footer whose offset depends on the
#: model.  A head-only window silently loses them on anything but a tiny part, so
#: both ends are read and searched in order.
_HEAD_BYTES = 300_000
_TAIL_BYTES = 300_000


def _gcode_windows(data: bytes) -> tuple[str, ...]:
    """Decode the head of the file and, when there is more, its tail."""

    head = data[:_HEAD_BYTES].decode("utf-8", errors="ignore")
    if len(data) <= _HEAD_BYTES:
        return (head,)
    tail = data[-_TAIL_BYTES:].decode("utf-8", errors="ignore")
    newline = tail.find("\n")  # drop the partial line the window started in
    return (head, tail[newline + 1 :] if newline >= 0 else tail)


def parse_gcode(path: Path) -> dict[str, Any]:
    """Read the metadata OrcaSlicer writes around the G-code."""
    data = path.read_bytes()
    windows = _gcode_windows(data)

    def _first(regex: re.Pattern[str]) -> re.Match[str] | None:
        for window in windows:
            match = regex.search(window)
            if match:
                return match
        return None

    def _number(regex: re.Pattern[str]) -> float | None:
        match = _first(regex)
        if not match:
            return None
        try:
            return float(match.group(1))
        except (TypeError, ValueError):
            return None

    tools = sorted(
        {
            int(match.group(1))
            for line in data.splitlines()
            if (match := _TOOL_RE.match(line.strip()))
        }
    )
    printer = _first(_PRINTER_RE)
    generated = _first(_GENERATED_RE)
    layers = _first(_LAYER_RE)
    total_time = _first(_ESTIMATED_TIME_RE) or _first(_TOTAL_TIME_RE)
    model_time = _first(_MODEL_TIME_RE)
    flavor = _first(_FLAVOR_RE)
    printable = _first(_PRINTABLE_RE)
    bed_mm = None
    if printable:
        points: list[tuple[float, float]] = []
        for item in printable.group(1).split(","):
            try:
                x_text, y_text = item.strip().split("x", 1)
                points.append((float(x_text), float(y_text)))
            except (TypeError, ValueError):
                points = []
                break
        if len(points) >= 3:
            xs = [point[0] for point in points]
            ys = [point[1] for point in points]
            bed_mm = [max(xs) - min(xs), max(ys) - min(ys)]

    warnings: list[str] = []
    if b"HEADER_BLOCK_START" not in data[:2048]:
        warnings.append("G-code has no HEADER_BLOCK_START marker")
    if len(data) < 4096:
        warnings.append(f"G-code is suspiciously small ({len(data)} bytes)")
    if not layers:
        warnings.append("G-code has no total layer number")
    if b"\nG28" not in data and b"\nG28\n" not in data and b"\nG28 " not in data[-200000:]:
        warnings.append("G-code has no homing command near the end")

    return {
        "printer_model": printer.group(1).strip() if printer else None,
        "generated_by": generated.group(1).strip() if generated else None,
        "total_layers": int(layers.group(1)) if layers else None,
        "estimated_seconds": _duration_seconds(total_time.group(1)) if total_time else None,
        "model_seconds": _duration_seconds(model_time.group(1)) if model_time else None,
        "filament_mm": _number(_FILAMENT_MM_RE),
        "filament_g": _number(_FILAMENT_G_RE),
        "filament_cm3": _number(_FILAMENT_CM3_RE),
        "max_z_mm": _number(_MAX_Z_RE),
        "gcode_flavor": flavor.group(1).strip() if flavor else None,
        "bed_mm": bed_mm,
        "bytes": len(data),
        "toolheads": tools,
        "warnings": warnings,
    }


def trim_unused_tool_macros(
    path: Path,
    *,
    used_tools: list[int] | None,
    flow_calibration: dict[str, Any] | None,
    slots: list[dict[str, Any]] | None = None,
    toolhead_count: int | None = None,
) -> dict[str, Any]:
    """Drop start-macro lines that heat/feed/calibrate unused toolheads.

    Vendor start macros often run a per-tool macro for every head (for example
    ``SM_PRINT_FLOW_CALIBRATE EXTRUDER=0..3``).  A print that only uses T0 pays
    for all four.  When the printer config opts in, remove the lines for tools
    the sliced G-code never uses, so enabling flow calibration only calibrates
    the heads that matter.
    """
    config = flow_calibration or {}
    if not config.get("trim_unused_tools"):
        return {"enabled": False, "removed_lines": 0}
    macros = {str(item).upper() for item in (config.get("tool_macros") or []) if str(item).strip()}
    used = {int(item) for item in (used_tools or [])}
    if not macros:
        return {"enabled": False, "removed_lines": 0, "reason": "no tool_macros configured"}
    if not used:
        return {"enabled": False, "removed_lines": 0, "reason": "no used toolheads detected"}

    # Slots are positional (G-code tool order).  A single-nozzle AMS machine
    # exposes several materials on one physical toolhead; calibrating that head
    # once is enough, and Orca/Bambu apply the per-filament K on each switch.
    physical: dict[int, int] = {}
    for tool in sorted(used):
        head = 0 if toolhead_count == 1 else tool
        if toolhead_count != 1 and slots and 0 <= tool < len(slots):
            value = slots[tool].get("toolhead") if isinstance(slots[tool], dict) else None
            if value is not None:
                head = int(value)
        physical.setdefault(head, tool)
    keep = set(physical.values())

    data = path.read_bytes()
    kept: list[bytes] = []
    removed: list[str] = []
    for line in data.splitlines(keepends=True):
        match = _TOOL_MACRO_RE.match(line.decode("utf-8", errors="ignore"))
        if match and match.group(1).upper() in macros and int(match.group(2)) not in keep:
            removed.append(match.group(0).strip())
            continue
        kept.append(line)
    if removed:
        path.write_bytes(b"".join(kept))
    return {
        "enabled": True,
        "macros": sorted(macros),
        "used_tools": sorted(used),
        "physical_toolheads": sorted(physical),
        "kept_tools": sorted(keep),
        "removed_lines": len(removed),
        "removed": removed[:12],
    }


def parse_machine_bed(machine: Path) -> tuple[float, float] | None:
    """Extract the printable bed size from a machine preset (axis-aligned)."""
    try:
        data = json.loads(machine.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        return None
    raw = data.get("printable_area")
    if not isinstance(raw, list) or len(raw) < 3:
        return None
    points: list[tuple[float, float]] = []
    for item in raw:
        try:
            x_text, y_text = str(item).split("x", 1)
            points.append((float(x_text), float(y_text)))
        except (ValueError, TypeError):
            return None
    xs = [point[0] for point in points]
    ys = [point[1] for point in points]
    return max(xs) - min(xs), max(ys) - min(ys)


@dataclass(slots=True)
class SliceResult:
    ok: bool
    exit_code: int | None = None
    duration_s: float = 0.0
    stdout: str = ""
    stderr: str = ""
    gcode: Path | None = None
    statistics: dict[str, Any] = field(default_factory=dict)
    metadata: dict[str, Any] = field(default_factory=dict)
    checks: dict[str, Any] = field(default_factory=dict)
    error: str | None = None
    timed_out: bool = False
    hint: str | None = None
    command: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    prepared: PreparedProfiles | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "ok": self.ok,
            "exit_code": self.exit_code,
            "duration_s": round(self.duration_s, 2),
            "timed_out": self.timed_out,
            "gcode": str(self.gcode) if self.gcode else None,
            "statistics": dict(self.statistics),
            "metadata": dict(self.metadata),
            "checks": dict(self.checks),
            "error": self.error,
            "hint": self.hint,
            "command": list(self.command),
            "warnings": list(self.warnings),
            "stdout_tail": self.stdout[-MAX_OUTPUT_CHARS:],
            "stderr_tail": self.stderr[-MAX_OUTPUT_CHARS:],
        }


def build_command(
    binary: Path,
    prepared: PreparedProfiles,
    *,
    stl: Path,
    outdir: Path,
    supports_statistics: bool,
) -> list[str]:
    command = [str(binary)]
    if prepared.datadir is not None:
        command += ["--datadir", str(prepared.datadir)]
    command += [
        "--load-settings",
        f"{prepared.machine};{prepared.process}",
        "--load-filaments",
        ";".join(str(item) for item in prepared.filament),
    ]
    if prepared.toolhead > 0:
        command += ["--load-filament-ids", str(prepared.toolhead + 1)]
    if supports_statistics:
        command.append("--export-statistics")
    command += ["--slice", "0", "--outputdir", str(outdir), str(stl)]
    return command


def _run_slicer(
    command: list[str], *, outdir: Path, budget: float
) -> tuple[int | None, str, str, bool]:
    """Run the slicer CLI once: ``(exit_code, stdout, stderr, timed_out)``."""

    try:
        with processes.child(command, cwd=str(outdir), env=clean_env()) as process:
            try:
                stdout, stderr = process.communicate(timeout=budget)
            except subprocess.TimeoutExpired:
                processes.terminate_tree(process)
                stdout, stderr = process.communicate()
                return None, stdout or "", stderr or "", True
            return process.returncode, stdout or "", stderr or "", False
    except OSError as exc:
        raise AdapterUnavailable(f"Could not start the slicer: {exc}") from exc


def _gcode_outputs(outdir: Path) -> list[Path]:
    return sorted(outdir.glob("*.gcode"), key=lambda item: item.stat().st_mtime)


def slice_stl(
    stl: Path,
    target: TargetSettings,
    workdir: Path,
    *,
    timeout_s: float | None = None,
    slicer_path: str | None = None,
    options: SliceOptions | None = None,
    flow_calibration: dict[str, Any] | None = None,
    slots: list[dict[str, Any]] | None = None,
    toolhead_count: int | None = None,
) -> SliceResult:
    """Slice ``stl`` with ``target`` and return G-code plus real statistics."""
    stl = Path(stl)
    if not stl.is_file():
        raise NotFound(f"Model not found: {stl}", hint="Build the revision first (model_build).")

    binary = find_slicer(slicer_path or target.slicer_path)
    if binary is None:
        raise AdapterUnavailable("No slicer found", hint=install_hint())
    info = probe_slicer(binary)
    if not info.found:
        raise AdapterUnavailable(
            f"Slicer did not start: {binary}",
            hint="; ".join(info.problems) or "Run it once from the GUI to finish setup.",
        )
    if info.problems:
        raise AdapterUnavailable(
            f"Slicer {binary.name} is not usable",
            hint="; ".join(info.problems),
        )

    workdir.mkdir(parents=True, exist_ok=True)
    prepared = prepare_profiles(target, workdir, options)
    outdir = workdir / "output"
    outdir.mkdir(parents=True, exist_ok=True)
    budget = float(timeout_s or target.timeout_s or DEFAULT_TIMEOUT_S)
    # A slicer can support a flag without being able to say so: OrcaSlicer on
    # Windows exits 0 with no --help output.  When the flags are unverified, ask
    # for the statistics file anyway and drop the flag if the run yields G-code.
    attempt_statistics = info.supports_statistics or not info.help_text_verified
    command = build_command(
        binary,
        prepared,
        stl=stl,
        outdir=outdir,
        supports_statistics=attempt_statistics,
    )

    started = time.monotonic()
    exit_code, stdout, stderr, timed_out = _run_slicer(command, outdir=outdir, budget=budget)
    retry_note: str | None = None
    if attempt_statistics and not timed_out and not _gcode_outputs(outdir):
        retry_note = (
            "the slicer did not accept --export-statistics (no G-code); "
            "it was sliced again without the flag"
        )
        command = build_command(
            binary,
            prepared,
            stl=stl,
            outdir=outdir,
            supports_statistics=False,
        )
        exit_code, stdout, stderr, timed_out = _run_slicer(
            command, outdir=outdir, budget=budget
        )
    elapsed = time.monotonic() - started

    gcodes = _gcode_outputs(outdir)
    statistics: dict[str, Any] = {}
    stats_files = sorted(
        (item for item in outdir.iterdir() if STATISTICS_RE.match(item.name)),
        key=lambda item: item.stat().st_mtime,
    )
    if stats_files:
        try:
            statistics = json.loads(stats_files[-1].read_text(encoding="utf-8-sig"))
        except (OSError, ValueError):
            statistics = {}

    warnings = list(prepared.warnings)
    if retry_note:
        warnings.append(retry_note)
    result = SliceResult(
        ok=False,
        exit_code=exit_code,
        duration_s=elapsed,
        stdout=stdout,
        stderr=stderr,
        command=command,
        timed_out=timed_out,
        warnings=warnings,
        prepared=prepared,
    )

    if timed_out:
        result.error = f"slicer exceeded the {budget:.0f}s budget"
        result.hint = "Raise targets.<name>.timeout_s or simplify the model."
        return result
    if not gcodes:
        # The probe could not read --help on this platform, so its note about
        # unverified flags belongs with the failure, not on every good slice.
        result.warnings.extend(info.warnings)
        result.error = f"slicer exited with code {exit_code} and produced no G-code"
        result.hint = (stderr or stdout)[-1200:].strip() or "Run slice_plan to check the profiles."
        return result

    gcode = gcodes[-1]
    metadata = parse_gcode(gcode)
    trim = trim_unused_tool_macros(
        gcode,
        used_tools=metadata.get("toolheads"),
        flow_calibration=flow_calibration,
        slots=slots,
        toolhead_count=toolhead_count,
    )
    metadata["tool_macro_trim"] = trim
    if trim.get("removed_lines"):
        metadata["bytes"] = gcode.stat().st_size
    summary = statistics.get("summary") if isinstance(statistics.get("summary"), dict) else {}
    if metadata.get("total_layers") is None and summary.get("layer_count"):
        metadata["total_layers"] = int(summary["layer_count"])
    if metadata.get("estimated_seconds") is None and summary.get("time"):
        metadata["estimated_seconds"] = int(round(float(summary["time"])))
    if metadata.get("filament_g") is None and summary.get("weight"):
        metadata["filament_g"] = float(summary["weight"])
    if metadata.get("filament_mm") is None:
        filaments = summary.get("filaments") or []
        if filaments and isinstance(filaments[0], dict) and filaments[0].get("length"):
            metadata["filament_mm"] = float(filaments[0]["length"])
    if metadata.get("filament_cm3") is None and summary.get("volume"):
        metadata["filament_cm3"] = round(float(summary["volume"]) / 1000.0, 3)
    result.warnings.extend(metadata.get("warnings", []))
    model_stats = mesh_stats(load_stl(stl))
    bed = parse_machine_bed(prepared.machine)
    if bed is None and metadata.get("bed_mm"):
        bed = tuple(metadata["bed_mm"])
    result.checks = {
        "gcode_bytes": metadata["bytes"],
        "layers": metadata["total_layers"],
        "estimated_seconds": metadata["estimated_seconds"],
        "filament_g": metadata["filament_g"],
        "printer_model": metadata["printer_model"],
        "gcode_flavor": metadata["gcode_flavor"],
        "model_bbox_mm": model_stats.get("bbox_mm"),
        "model_volume_mm3": model_stats.get("volume_mm3"),
        "model_watertight": model_stats.get("watertight"),
        "bed_mm": list(bed) if bed else None,
        "tool_macro_trim": metadata.get("tool_macro_trim"),
    }
    if bed and model_stats.get("bbox_mm"):
        width, depth = bed
        bbox = model_stats["bbox_mm"]
        if bbox[0] > width or bbox[1] > depth:
            result.warnings.append(
                f"model footprint {bbox[0]:.1f}x{bbox[1]:.1f} mm exceeds the "
                f"{width:.0f}x{depth:.0f} mm bed"
            )
    if (
        metadata.get("printer_model")
        and target.printer_model
        and metadata["printer_model"].strip() != target.printer_model.strip()
    ):
        result.warnings.append(
            f"G-code says printer_model={metadata['printer_model']!r}, "
            f"target says {target.printer_model!r}"
        )

    result.ok = exit_code == 0
    result.gcode = gcode
    result.metadata = metadata
    result.statistics = statistics
    if not result.ok:
        result.error = f"slicer exited with code {exit_code}"
        result.hint = (stderr or stdout)[-1200:].strip() or None
    return result


class SliceStore:
    """Store slice records and their G-code under ``<workspace>/slices``."""

    def __init__(self, workspace: Workspace) -> None:
        self.workspace = workspace

    def directory(self, slice_id: str) -> Path:
        return self.workspace.slices_dir / validate_slice_id(slice_id)

    def record_path(self, slice_id: str) -> Path:
        return self.directory(slice_id) / "slice.json"

    def save(self, record: dict[str, Any]) -> dict[str, Any]:
        slice_id = validate_slice_id(str(record["slice_id"]))
        path = self.record_path(slice_id)
        atomic_write_text(path, json.dumps(record, ensure_ascii=False, indent=2) + "\n")
        return record

    def load(self, slice_id: str) -> dict[str, Any]:
        path = self.record_path(slice_id)
        if not path.is_file():
            raise NotFound(
                f"Slice not found: {slice_id}",
                hint="Slices are produced by slice_run; use job_status for a running job.",
            )
        return json.loads(path.read_text(encoding="utf-8-sig"))

    def save_result(
        self,
        *,
        slice_id: str,
        asset_id: str,
        revision: str,
        target_name: str,
        target: TargetSettings,
        result: SliceResult,
        slicer: SlicerInfo,
        prepared: PreparedProfiles | None = None,
        options: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        resolved = prepared or result.prepared
        if resolved is None:
            machine, process, filaments = resolve_profiles(target)
            resolved = PreparedProfiles(machine=machine, process=process, filament=filaments)
        record = {
            "slice_id": slice_id,
            "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "asset_id": asset_id,
            "revision": revision,
            "target": target_name,
            "printer_model": target.printer_model,
            "slicer": slicer.to_dict(),
            "profiles": resolved.to_dict(),
            "options": options if options is not None else resolved.options,
            "command": result.command,
            "ok": result.ok,
            "exit_code": result.exit_code,
            "duration_s": round(result.duration_s, 2),
            "timed_out": result.timed_out,
            "error": result.error,
            "gcode": None,
            "metadata": result.metadata,
            "statistics": result.statistics,
            "checks": result.checks,
            "warnings": result.warnings,
        }
        if result.gcode:
            directory = self.directory(slice_id)
            directory.mkdir(parents=True, exist_ok=True)
            stored = directory / result.gcode.name
            if result.gcode.resolve() != stored.resolve():
                shutil.copyfile(result.gcode, stored)
            data = stored.read_bytes()
            record["gcode"] = {
                "file": stored.name,
                "bytes": len(data),
                "sha256": hashlib.sha256(data).hexdigest(),
            }
            statistics_file = result.gcode.with_name(result.gcode.stem + ".statistics.json")
            if statistics_file.is_file():
                stored_statistics = directory / statistics_file.name
                if statistics_file.resolve() != stored_statistics.resolve():
                    shutil.copyfile(statistics_file, stored_statistics)
                record["statistics_file"] = stored_statistics.name
        return self.save(record)
