def normalise_build_plate(value: str) -> str:
    """Map a user-facing plate name to the canonical id ('' means unknown)."""
    text = (value or "").strip().lower().replace(" ", "_").replace("-", "_")
    if not text:
        return ""
    if text in BUILD_PLATES:
        return text
    if text in BUILD_PLATE_ALIASES:
        return BUILD_PLATE_ALIASES[text]
    known = ", ".join(sorted(BUILD_PLATES))
    raise InvalidArgument(f"Unknown build plate: {value!r}", hint=f"Known plates: {known}.")


#: strength preset -> (walls, top shells, bottom shells)
STRENGTH_PRESETS: dict[str, tuple[int, int, int]] = {
    "light": (2, 3, 2),
    "normal": (3, 4, 3),
    "strong": (4, 5, 4),
}


@dataclass(slots=True)
class SliceOptions:
    """User-facing process/material choices for one slice.

    ``None`` means "keep the preset value"; the server converts omitted MCP
    arguments to ``None``.  Material implies conservative nozzle/bed
    temperatures, which can still be overridden explicitly.
    """

    material: str = ""
    layer_height: float | None = None
    infill: str = ""
    infill_density: float | None = None
    walls: int | None = None
    top_shells: int | None = None
    bottom_shells: int | None = None
    strength: str = ""
    bed_temp: int | None = None
    nozzle_temp: int | None = None
    toolhead: int = 0
    build_plate: str = ""
    flow_ratio: float | None = None
    pressure_advance: float | None = None
    line_width: float | None = None
    outer_wall_line_width: float | None = None
    inner_wall_line_width: float | None = None
    top_surface_line_width: float | None = None
    arc_fitting: bool = False
    fan_speed: int | None = None
    aux_fan_speed: int | None = None
    fan_first_layers: int | None = None

    def resolved(self) -> dict[str, Any]:
        material = self.material.strip().upper()
        plate = normalise_build_plate(self.build_plate)
        nozzle = self.nozzle_temp
        bed = self.bed_temp
        if material:
            pair = MATERIAL_TEMPS.get(material)
            if pair is None and nozzle is None and bed is None:
                raise InvalidArgument(
                    f"Unknown material: {material}",
                    hint=(
                        "Use one of "
                        + ", ".join(sorted(MATERIAL_TEMPS))
                        + ", or pass nozzle_temp/bed_temp explicitly."
                    ),
                )
            if pair is not None:
                nozzle = nozzle if nozzle is not None else pair[0]
                bed = bed if bed is not None else pair[1]
                if plate and self.bed_temp is None:
                    bed = max(0, bed + int(BUILD_PLATES[plate]["adjust"]))
        if nozzle is not None and not 150 <= int(nozzle) <= 350:
            raise InvalidArgument("nozzle_temp must be between 150 and 350 °C")
        if bed is not None and not 0 <= int(bed) <= 150:
            raise InvalidArgument("bed_temp must be between 0 and 150 °C")

        layer = self.layer_height
        if layer is not None and not 0.05 <= float(layer) <= 1.0:
            raise InvalidArgument("layer_height must be between 0.05 and 1.0 mm")
        density = self.infill_density
        if density is not None and not 0 <= float(density) <= 100:
            raise InvalidArgument("infill_density must be between 0 and 100 percent")
        infill = self.infill.strip().lower()
        if infill and infill not in INFILL_PATTERNS:
            raise InvalidArgument(
                f"Unknown infill pattern: {infill}",
                hint="Use one of " + ", ".join(sorted(INFILL_PATTERNS)) + ".",
            )

        strength = self.strength.strip().lower()
        walls = self.walls
        top = self.top_shells
        bottom = self.bottom_shells
        if strength:
            preset = STRENGTH_PRESETS.get(strength)
            if preset is None:
                raise InvalidArgument(
                    f"Unknown strength: {strength}",
                    hint="Use light, normal or strong, or pass walls/top_shells/bottom_shells.",
                )
            walls = walls if walls is not None else preset[0]
            top = top if top is not None else preset[1]
            bottom = bottom if bottom is not None else preset[2]
        if walls is not None and not 1 <= int(walls) <= 10:
            raise InvalidArgument("walls must be between 1 and 10")
        if top is not None and not 1 <= int(top) <= 20:
            raise InvalidArgument("top_shells must be between 1 and 20")
        if bottom is not None and not 1 <= int(bottom) <= 20:
            raise InvalidArgument("bottom_shells must be between 1 and 20")
        flow_ratio = self.flow_ratio
        if flow_ratio is not None and not 0.5 <= float(flow_ratio) <= 1.5:
            raise InvalidArgument("flow_ratio must be between 0.5 and 1.5")
        pressure_advance = self.pressure_advance
        if pressure_advance is not None and not 0.0 <= float(pressure_advance) <= 0.2:
            raise InvalidArgument("pressure_advance must be between 0 and 0.2")
        widths = {
            "line_width": self.line_width,
            "outer_wall_line_width": self.outer_wall_line_width,
            "inner_wall_line_width": self.inner_wall_line_width,
            "top_surface_line_width": self.top_surface_line_width,
        }
        for name, value in widths.items():
            if value is not None and not 0.2 <= float(value) <= 1.0:
                raise InvalidArgument(f"{name} must be between 0.2 and 1.0 mm")
        for name, value in (("fan_speed", self.fan_speed), ("aux_fan_speed", self.aux_fan_speed)):
            if value is not None and not 0 <= int(value) <= 100:
                raise InvalidArgument(f"{name} must be between 0 and 100 percent")
        if self.fan_first_layers is not None and not 0 <= int(self.fan_first_layers) <= 10:
            raise InvalidArgument("fan_first_layers must be between 0 and 10")
        if not 0 <= int(self.toolhead) <= 8:
            raise InvalidArgument("toolhead must be between 0 and 8")

        return {
            "material": material or None,
            "layer_height": float(layer) if layer is not None else None,
            "infill": infill or None,
            "infill_density": float(density) if density is not None else None,
            "walls": int(walls) if walls is not None else None,
            "top_shells": int(top) if top is not None else None,
            "bottom_shells": int(bottom) if bottom is not None else None,
            "strength": strength or None,
            "bed_temp": int(bed) if bed is not None else None,
            "nozzle_temp": int(nozzle) if nozzle is not None else None,
            "toolhead": int(self.toolhead),
            "build_plate": plate or None,
            "flow_ratio": float(flow_ratio) if flow_ratio is not None else None,
            "pressure_advance": (float(pressure_advance) if pressure_advance is not None else None),
            **{
                name: (round(float(value), 3) if value is not None else None)
                for name, value in widths.items()
            },
            "arc_fitting": bool(self.arc_fitting),
            "fan_speed": int(self.fan_speed) if self.fan_speed is not None else None,
            "aux_fan_speed": int(self.aux_fan_speed) if self.aux_fan_speed is not None else None,
            "fan_first_layers": (
                int(self.fan_first_layers) if self.fan_first_layers is not None else None
            ),
        }

    def process_overrides(self) -> dict[str, str]:
        data = self.resolved()
        overrides: dict[str, str] = {}
        if data["layer_height"] is not None:
            overrides["layer_height"] = f"{data['layer_height']:g}"
        if data["infill"]:
            overrides["sparse_infill_pattern"] = data["infill"]
        if data["infill_density"] is not None:
            overrides["sparse_infill_density"] = f"{int(data['infill_density'])}%"
        if data["walls"] is not None:
            overrides["wall_loops"] = str(data["walls"])
        if data["top_shells"] is not None:
            overrides["top_shell_layers"] = str(data["top_shells"])
        if data["bottom_shells"] is not None:
            overrides["bottom_shell_layers"] = str(data["bottom_shells"])
        if data["build_plate"]:
            overrides["curr_bed_type"] = BUILD_PLATES[data["build_plate"]]["label"]
        for name in (
            "line_width",
            "outer_wall_line_width",
            "inner_wall_line_width",
            "top_surface_line_width",
        ):
            if data.get(name) is not None:
                overrides[name] = f"{data[name]:g}"
        if data.get("arc_fitting"):
            overrides["enable_arc_fitting"] = "1"
        return overrides

    def filament_overrides(self) -> dict[str, str]:
        data = self.resolved()
        overrides: dict[str, str] = {}
        if data["material"]:
            overrides["filament_type"] = data["material"]
        if data["nozzle_temp"] is not None:
            nozzle = str(data["nozzle_temp"])
            # OrcaSlicer reads the nozzle_temperature_* keys; the Bambu-style
            # temperature keys are kept for forks that still use them.
            overrides.update(
                {
                    "nozzle_temperature": nozzle,
                    "nozzle_temperature_initial_layer": nozzle,
                    "temperature": nozzle,
                    "first_layer_temperature": nozzle,
                }
            )
        if data["flow_ratio"] is not None:
            overrides["filament_flow_ratio"] = f"{data['flow_ratio']:.3f}".rstrip("0").rstrip(".")
        if data["pressure_advance"] is not None:
            overrides["enable_pressure_advance"] = "1"
            overrides["pressure_advance"] = f"{data['pressure_advance']:.4f}".rstrip("0").rstrip(
                "."
            )
        if data["bed_temp"] is not None:
            bed = str(data["bed_temp"])
            overrides.update(
                {
                    "bed_temperature": bed,
                    "first_layer_bed_temperature": bed,
                }
            )
            if data["build_plate"]:
                key = str(BUILD_PLATES[data["build_plate"]]["key"])
                overrides[key] = bed
                overrides[f"{key}_initial_layer"] = bed
            else:
                for plate in (
                    "hot_plate",
                    "textured_plate",
                    "cool_plate",
                    "eng_plate",
                    "supertack_plate",
                    "graphic_effect_plate",
                ):
                    overrides[f"{plate}_temp"] = bed
                    overrides[f"{plate}_temp_initial_layer"] = bed
        if data.get("fan_speed") is not None:
            overrides["fan_max_speed"] = str(data["fan_speed"])
            overrides["fan_min_speed"] = str(data["fan_speed"])
        if data.get("aux_fan_speed") is not None:
            overrides["additional_cooling_fan_speed"] = str(data["aux_fan_speed"])
        if data.get("fan_first_layers") is not None:
            overrides["close_fan_the_first_x_layers"] = str(data["fan_first_layers"])
        return overrides


def new_slice_id() -> str:
    """Return a fresh slice id such as ``s_20261114T083000Z_ab12cd``."""
    stamp = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
    return f"s_{stamp}_{os.urandom(3).hex()}"


def validate_slice_id(value: str) -> str:
    text = (value or "").strip()
    if not SLICE_ID_RE.match(text):
        raise InvalidArgument(
            f"Invalid slice id: {value!r}",
            hint="Slice ids look like s_20261114T083000Z_ab12cd; use slice_inspect.",
        )
    return text


def windows_slicer_candidates() -> tuple[Path, ...]:
    """OrcaSlicer / Snapmaker Orca installs on Windows, most likely first.

    The vendor installers put the GUI binary in ``%PROGRAMFILES%`` (machine) or
    ``%LOCALAPPDATA%\\Programs`` (per-user); both ship a CLI-capable executable,
    which is all ``slice_stl`` needs.
    """

    roots: list[Path] = []
    for env_name in ("PROGRAMFILES", "PROGRAMFILES(X86)", "LOCALAPPDATA"):
        raw = os.environ.get(env_name)
        if not raw:
            continue
        base = Path(raw)
        if env_name == "LOCALAPPDATA":
            base = base / "Programs"
        for folder, exe in (
            ("OrcaSlicer", "orca-slicer.exe"),
            ("OrcaSlicer", "OrcaSlicer.exe"),
            ("Snapmaker Orca", "Snapmaker_Orca.exe"),
            ("Snapmaker_Orca", "Snapmaker_Orca.exe"),
            ("OrcaSlicer", os.path.join("bin", "orca-slicer.exe")),
        ):
            roots.append(base / folder / exe)
    return tuple(roots)


def slicer_candidates() -> tuple[Path, ...]:
    """Every install path worth probing on this platform."""

    if processes.IS_WINDOWS:
        return windows_slicer_candidates()
    return tuple(Path(item).expanduser() for item in SLICER_CANDIDATES)


def find_slicer(explicit: str | None = None) -> Path | None:
    """Locate the slicer binary: explicit config first, then known paths."""
    if explicit:
        path = Path(explicit).expanduser()
        if not path.is_file():
            raise InvalidArgument(
                f"Slicer not found: {path}",
                hint="Set targets.<name>.slicer_path to the OrcaSlicer binary.",
            )
        return path

    for path in slicer_candidates():
        if path.is_file():
            return path

    for name in SLICER_PROGRAM_NAMES:
        found = shutil.which(name)
        if found:
            return Path(found)
    return None


def install_hint() -> str:
    """Where to get a slicer, worded for this platform."""

