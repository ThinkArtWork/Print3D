def test_parse_gcode_extracts_metadata(tmp_path: Path) -> None:
    path = tmp_path / "plate_1.gcode"
    lines = [
        "; HEADER_BLOCK_START",
        "; generated by OrcaSlicer-2.5.0 on 2026-11-14 at 08:00:00",
        "; printer_model = Bambu Lab A1",
        "; total layer number: 50",
        "; filament used [mm] = 717.67",
        "; filament used [g] = 2.18",
        "; filament used [cm3] = 1.73",
        "; max_z_height: 10.00",
        "; gcode_flavor = marlin",
        "; total estimated time: 13m 47s",
        "; model printing time: 13m 30s",
        "; HEADER_BLOCK_END",
        "G28",
        "T0",
        "G1 X10 Y10 E1",
        "T4",
    ]
    lines += ["; " + ("x" * 100) for _ in range(60)]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    metadata = parse_gcode(path)
    assert metadata["printer_model"] == "Bambu Lab A1"
    assert metadata["total_layers"] == 50
    assert metadata["estimated_seconds"] == 13 * 60 + 47
    assert metadata["model_seconds"] == 13 * 60 + 30
    assert metadata["filament_mm"] == pytest.approx(717.67)
    assert metadata["filament_g"] == pytest.approx(2.18)
    assert metadata["toolheads"] == [0, 4]
    assert metadata["warnings"] == []


