def test_prepare_profiles_applies_overrides_to_a_private_copy(tmp_path: Path) -> None:
    machine, process, filament, root = _vendor(tmp_path)
    target = TargetSettings(
        printer_model="Fake A1",
        machine=str(machine),
        process=str(process),
        filament=[str(filament)],
        overrides={"layer_height": 0.16, "supports_enable": True},
    )
    prepared = prepare_profiles(target, tmp_path / "work")
    assert prepared.datadir == tmp_path / "work" / "datadir"
