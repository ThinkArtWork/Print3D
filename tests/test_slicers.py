FAKE_SLICER = f"""\
#!{sys.executable}
import json, os, sys, time

args = sys.argv[1:]
if "--help" in args:
    print("OrcaSlicer-2.5.0")
    print("Usage: OrcaSlicer [options]")
    for flag in ("--load-settings", "--load-filaments", "--export-statistics",
                 "--datadir", "--slice", "--outputdir"):
        print("  " + flag)
    sys.exit(0)

outdir = args[args.index("--outputdir") + 1]
stl = args[-1]
os.makedirs(outdir, exist_ok=True)
if os.environ.get("FAKE_SLICER_FAIL"):
    print("fake slicer failure", file=sys.stderr)
    sys.exit(7)
if os.environ.get("FAKE_SLICER_SLEEP"):
    time.sleep(float(os.environ["FAKE_SLICER_SLEEP"]))

name = os.path.splitext(os.path.basename(stl))[0]
header = [
    "; HEADER_BLOCK_START",
    "; generated by OrcaSlicer-2.5.0 on 2026-11-14 at 08:00:00",
    "; printer_model = Fake A1",
    "; printable_area = 256x256",
    "; total layer number: 50",
    "; filament used [mm] = 717.67",
    "; filament used [g] = 2.18",
    "; filament used [cm3] = 1.73",
    "; max_z_height: 10.00",
    "; gcode_flavor = marlin",
    "; total estimated time: 13m 47s",
    "; model printing time: 13m 30s",
    "; HEADER_BLOCK_END",
    "G28",
    "G90",
]
header += ["; padding " + ("x" * 80) for _ in range(60)]
header += ["G1 X10 Y10 E1.0", "G1 X20 Y10 E2.0", "M84"]
with open(os.path.join(outdir, name + ".gcode"), "w", encoding="utf-8") as handle:
    handle.write("\\n".join(header) + "\\n")
if "--export-statistics" in args:
    with open(os.path.join(outdir, name + ".statistics.json"), "w", encoding="utf-8") as handle:
        json.dump({{"summary": {{"layer_count": 50, "weight": 2.18}}}}, handle)
"""


def _fake_slicer(tmp_path: Path) -> Path:
    script = tmp_path / "fake-orca"
    script.write_text(FAKE_SLICER, encoding="utf-8")
    script.chmod(0o755)
    return script


def _vendor(tmp_path: Path) -> tuple[Path, Path, Path, Path]:
    root = tmp_path / "data"
    vendor = root / "system" / "FakeVendor"
    machine = vendor / "machine" / "Fake A1.json"
    process = vendor / "process" / "0.20mm Standard.json"
    filament = vendor / "filament" / "PLA @A1.json"
    for path in (machine, process, filament):
        path.parent.mkdir(parents=True, exist_ok=True)
    machine.write_text(
        json.dumps(
            {
                "printer_model": "Fake A1",
                "printable_area": ["0x0", "256x0", "256x256", "0x256"],
                "inherits": "fdm_machine_common",
            }
        ),
        encoding="utf-8",
    )
    process.write_text(
        json.dumps({"layer_height": "0.2", "wall_loops": "2", "from": "system"}),
        encoding="utf-8",
    )
    filament.write_text(json.dumps({"filament_type": "PLA", "from": "system"}), encoding="utf-8")
    (root / "system" / "FakeVendor.json").write_text(
        json.dumps({"name": "FakeVendor", "version": "01.00.00.00"}), encoding="utf-8"
    )
    return machine, process, filament, root


def _target(tmp_path: Path, **overrides) -> TargetSettings:
    machine, process, filament, _ = _vendor(tmp_path)
    values = {
        "printer_model": "Fake A1",
        "slicer": "orca",
        "slicer_path": str(_fake_slicer(tmp_path)),
        "machine": str(machine),
        "process": str(process),
        "filament": [str(filament)],
        "timeout_s": 30,
    }
    values.update(overrides)
    return TargetSettings(**values)


