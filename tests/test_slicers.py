    assert json.loads(process.read_text())["layer_height"] == "0.2"
    assert (prepared.datadir / "system" / "FakeVendor.json").is_file()
    assert Path(prepared.machine).is_file()
    assert Path(prepared.filament[0]).is_file()
    assert prepared.warnings


