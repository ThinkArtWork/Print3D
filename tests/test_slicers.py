def test_slice_stl_produces_gcode_and_real_checks(tmp_path: Path) -> None:
    target = _target(tmp_path)
    stl = tmp_path / "model.stl"
    write_stl(stl)
    result = slice_stl(stl, target, tmp_path / "work", timeout_s=20)
    assert result.ok is True
    assert result.exit_code == 0
    assert result.gcode is not None and result.gcode.is_file()
    assert result.metadata["total_layers"] == 50
    assert result.metadata["printer_model"] == "Fake A1"
    assert result.statistics["summary"]["layer_count"] == 50
    assert result.checks["gcode_bytes"] > 0
    assert result.checks["printer_model"] == "Fake A1"
    assert result.checks["model_volume_mm3"] > 0


def test_slice_stl_reports_a_failed_slicer(tmp_path: Path, monkeypatch) -> None:
    target = _target(tmp_path)
    stl = tmp_path / "model.stl"
    write_stl(stl)
